#!/usr/bin/env bash
# Regenerate containers/requirements.lock: exact versions + sha256 hashes for the runtime
# dependencies, resolved for CPython 3.12 on linux x86_64 (the container's interpreter).
# Uses pip's resolver report only; nothing is installed.
set -euo pipefail
cd "$(dirname "$0")/.."
report="$(mktemp)"
trap 'rm -f "$report"' EXIT
.venv/bin/python -m pip install --quiet --dry-run --ignore-installed --only-binary=:all: \
    --python-version 3.12 --implementation cp \
    --platform manylinux_2_28_x86_64 --platform manylinux_2_17_x86_64 --platform manylinux2014_x86_64 \
    --report "$report" \
    "pydantic>=2.7,<3" "pyyaml>=6,<7" "agent-framework-core==1.22.0" "fastapi==0.156.4" "uvicorn==0.54.0"
.venv/bin/python - "$report" > containers/requirements.lock <<'PY'
import json, sys
report = json.load(open(sys.argv[1]))
print("# Generated by scripts/lock_requirements.sh - do not edit by hand.")
print("# Installed in the container with: pip install --require-hashes --only-binary=:all:")
for item in sorted(report["install"], key=lambda i: i["metadata"]["name"].lower()):
    digest = item["download_info"]["archive_info"]["hashes"]["sha256"]
    print(f'{item["metadata"]["name"]}=={item["metadata"]["version"]} \\\n    --hash=sha256:{digest}')
PY
echo "wrote containers/requirements.lock ($(grep -c '==' containers/requirements.lock) packages)"
