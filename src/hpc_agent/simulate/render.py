"""Write a simulated scenario as a site export, and its labels apart from it.

    <out>/export/<id>/incident.json            the ticket (what the user and monitoring said)
    <out>/export/<id>/logs/slurmctld.log       [YYYY-MM-DDTHH:MM:SS.mmm] message
    <out>/export/<id>/logs/slurmd/<node>.log   [YYYY-MM-DDTHH:MM:SS.mmm] message
    <out>/export/<id>/logs/pjm.log             [YYYY-MM-DDTHH:MM:SS.mmm] message   (tcs-fx1000, approximated)
    <out>/export/<id>/logs/syslog              <RFC 3339 time> <host> <tag>: message   (central rsyslog)
    <out>/export/<id>/commands/sacct.txt       sacct -P style
    <out>/export/<id>/commands/sinfo.txt       sinfo -N -o "%N|%T|%E|%H" style
    <out>/export/<id>/commands/lfs_df.txt      lfs df style
    <out>/export/<id>/commands/ibstat.txt      ibstat + perfquery style, per job node
    <out>/export/<id>/commands/dcgmi_health.txt  per-GPU health summary, GPU job nodes only
    tcs-fx1000 instead of sacct/sinfo/ibstat (approximated formats, see simulate/platform.py):
    <out>/export/<id>/commands/pjstat.txt      CSV job history (pjstat -H style)
    <out>/export/<id>/commands/node_state.txt  NODELIST|STATE|REASON|TIMESTAMP
    <out>/export/<id>/commands/tofu_links.txt  per node: "## <node>", "TNIn port X: state=.. link_down_count=.. crc_errors=.."
    <out>/labels/<id>.json                     the answer (never read by the import adapter)

Every file starts with a '# SYNTHETIC' line. Line numbers in labels are physical line numbers.
"""

from __future__ import annotations

import json
from datetime import timedelta
from pathlib import Path

from hpc_agent.simulate.catalog import FAULT_FUNCTIONS, hostlist
from hpc_agent.simulate.noise import background, distractors
from hpc_agent.simulate.scenario import Labels, Scenario
from hpc_agent.simulate.world import Line, World, build_world


def _header(sc: Scenario, what: str) -> str:
    return f"# SYNTHETIC {what}: generated by hpc-agent simulate (scenario {sc.scenario_id}, seed {sc.seed}); not real tool output"


def _bracket(line: Line) -> str:
    return f"[{line.when.strftime('%Y-%m-%dT%H:%M:%S')}.{line.when.microsecond // 1000:03d}] {line.text}"


def _syslog(line: Line) -> str:
    return f"{line.when.strftime('%Y-%m-%dT%H:%M:%S')}.{line.when.microsecond:06d}+00:00 {line.node} {line.text}"


def _duration(delta: timedelta) -> str:
    seconds = int(delta.total_seconds())
    days, rest = divmod(seconds, 86400)
    text = f"{rest // 3600:02d}:{rest % 3600 // 60:02d}:{rest % 60:02d}"
    return f"{days}-{text}" if days else text


def _iso(when) -> str:
    return when.strftime("%Y-%m-%dT%H:%M:%S")


def _sacct(w: World) -> list[str]:
    j = w.job
    elapsed, nodes = _duration(j.end - j.start), hostlist(j.nodes)
    rows = ["JobID|JobName|Partition|State|ExitCode|Elapsed|Timelimit|Start|End|NodeList",
            f"{j.job_id}|{j.name}|{j.partition}|{j.state}|{j.exit_code}|{elapsed}|{_duration(j.timelimit)}|"
            f"{_iso(j.start)}|{_iso(j.end)}|{nodes}",
            f"{j.job_id}.batch|batch||{j.state.split()[0]}|{j.exit_code}|{elapsed}||{_iso(j.start)}|{_iso(j.end)}|"
            f"{j.nodes[0]}",
            f"{j.job_id}.0|{j.name}||{j.state.split()[0]}|{j.exit_code}|{elapsed}||{_iso(j.start)}|{_iso(j.end)}|{nodes}"]
    return rows


def _sinfo(w: World) -> list[str]:
    rows = ["NODELIST|STATE|REASON|TIMESTAMP"]
    shown = [n for n in w.nodes if n in w.job.nodes or w.node_state[n][0] != "IDLE"]
    for node in shown:
        state, reason, when = w.node_state[node]
        rows.append(f"{node}|{state.lower()}|{reason or 'none'}|{_iso(when) if when else 'Unknown'}")
    return rows


def _lfs_df(w: World) -> list[str]:
    rows = [f"# collected {_iso(w.incident_time)}Z",
            "UUID                   1K-blocks        Used   Available Use% Mounted on"]
    size = 120_000_000_000
    total_used = 0
    rows.append(f"{w.p.filesystem}-MDT0000_UUID   4294967296   214748364  4080218932   5% /{w.p.filesystem}[MDT:0]")
    for i, ost in enumerate(w.osts):
        used = size * w.ost_used[ost] // 100
        total_used += used
        rows.append(f"{w.p.filesystem}-{ost}_UUID {size:>14} {used:>14} {size - used:>14} {w.ost_used[ost]:>3}% "
                    f"/{w.p.filesystem}[OST:{i}]")
    total = size * len(w.osts)
    rows.append("")
    rows.append(f"filesystem_summary:  {total:>14} {total_used:>14} {total - total_used:>14} "
                f"{round(100 * total_used / total):>3}% /{w.p.filesystem}")
    return rows


def _ibstat(w: World) -> list[str]:
    rows = [f"# collected {_iso(w.incident_time)}Z"]
    for node in w.job.nodes:
        p = w.ports[node]
        rows += [f"## {node}", "CA 'mlx5_0'", "\tPort 1:", f"\t\tState: {p.state}", f"\t\tPhysical state: {p.physical}",
                 "\t\tRate: 200", "## perfquery mlx5_0 1",
                 f"SymbolErrorCounter:..............{p.symbol_errors}",
                 f"LinkDownedCounter:...............{p.link_downed}",
                 f"PortRcvErrors:...................{p.rcv_errors}",
                 f"PortXmitDiscards:................{p.xmit_discards}"]
    return rows


def _dcgmi(w: World) -> list[str]:
    rows = [f"# collected {_iso(w.incident_time)}Z"]
    for node in w.job.nodes:
        if node not in w.gpus:
            continue
        rows.append(f"## {node}")
        for g in w.gpus[node]:
            rows.append(f"GPU {g.index} | PCI {g.pci}.0 | {g.health} | temp {g.temperature_c} C | DBE {g.dbe} |"
                        + (f" {g.message}" if g.message else ""))
    return rows


_PJM_REASON = {"TIMEOUT": "ELAPSE LIMIT EXCEEDED", "OUT_OF_MEMORY": "MEMORY LIMIT EXCEEDED",
               "CANCELLED by 0": "DELETED BY ADMINISTRATOR", "NODE_FAIL": "NODE DOWN"}
_PJM_SIGNAL = {"TIMEOUT": "9", "OUT_OF_MEMORY": "9", "CANCELLED by 0": "15", "NODE_FAIL": "9"}


def _pjstat(w: World) -> list[str]:
    j = w.job
    code, sig = j.exit_code.split(":")
    sig = _PJM_SIGNAL.get(j.state, sig)
    status = "CCL" if j.state.startswith("CANCELLED") else "EXT"
    reason = _PJM_REASON.get(j.state, "-")
    return ["JOB_ID,JOB_NAME,MD,ST,START_DATE,END_DATE,ELAPSE_TIM,ELAPSE_LIM,NODE,NODE_LIST,PJM_CODE,END_CODE,SIGNAL,REASON",
            f"{j.job_id},{j.name},NM,{status},{_iso(j.start)},{_iso(j.end)},{_duration(j.end - j.start)},"
            f"{_duration(j.timelimit)},{len(j.nodes)},{hostlist(j.nodes)},{0 if reason == '-' else 1},{code},{sig},{reason}"]


def _node_state(w: World) -> list[str]:
    rows = ["NODELIST|STATE|REASON|TIMESTAMP"]
    for node in [n for n in w.nodes if n in w.job.nodes or w.node_state[n][0] != "IDLE"]:
        state, reason, when = w.node_state[node]
        state = {"IDLE": "ACTIVE", "DRAINED": "STOP", "DOWN*": "DOWN"}.get(state, state)
        rows.append(f"{node}|{state}|{reason or 'none'}|{_iso(when) if when else 'Unknown'}")
    return rows


def _tofu(w: World) -> list[str]:
    rows = [f"# collected {_iso(w.incident_time)}Z"]
    for node in w.job.nodes:
        p = w.ports[node]
        rows += [f"## {node}", f"TNI2 port C: state={'up' if p.state == 'Active' else 'down'} "
                 f"link_down_count={p.link_downed} crc_errors={p.symbol_errors + p.rcv_errors}"]
    return rows


def generate(sc: Scenario, out: Path) -> Labels:
    """Write <out>/export/<id>/ and <out>/labels/<id>.json; return the labels."""
    w = build_world(sc)
    spec = FAULT_FUNCTIONS[sc.fault](w)
    background(w)
    distractors(w)

    base = out / "export" / sc.scenario_id
    files: dict[str, list[Line]] = {f"logs/{w.p.scheduler_source}.log": [], "logs/syslog": []}
    for line in w.lines:
        if line.source == "slurmd":
            files.setdefault(f"logs/slurmd/{line.node}.log", []).append(line)
        else:
            files["logs/syslog" if line.source == "syslog" else f"logs/{line.source}.log"].append(line)

    key_lines: list[str] = []
    total = 0
    for relative, lines in sorted(files.items()):
        lines.sort(key=lambda x: (x.when, x.text))
        fmt = _syslog if relative == "logs/syslog" else _bracket
        source = "slurmd" if relative.startswith("logs/slurmd/") else relative.removeprefix("logs/").removesuffix(".log")
        text = [_header(sc, source)] + [fmt(line) for line in lines]
        for number, line in enumerate(lines, start=2):
            if line.key:
                key_lines.append(f"{source}:{line.node}:{number}")
        total += len(lines)
        _write(base / relative, text)

    tcs = w.p.name == "tcs-fx1000"
    commands = {"lfs_df.txt": _lfs_df(w)}
    commands |= {"node_state.txt": _node_state(w), "tofu_links.txt": _tofu(w)} if tcs else \
        {"sinfo.txt": _sinfo(w), "ibstat.txt": _ibstat(w)}
    if w.export_sacct:
        commands["pjstat.txt" if tcs else "sacct.txt"] = _pjstat(w) if tcs else _sacct(w)
    if any(n in w.gpus for n in w.job.nodes):
        commands["dcgmi_health.txt"] = _dcgmi(w)
    for name, rows in commands.items():
        _write(base / "commands" / name, [_header(sc, name.removesuffix(".txt"))] + rows)

    incident = {"incident_id": sc.scenario_id, "timestamp": _iso(w.incident_time) + "Z", "system": "HPC",
                "job_id": str(w.job.job_id), "severity": "medium", "symptoms": [w.user_report],
                "alerts": w.alerts, "operator_notes": []}
    _write(base / "incident.json", [json.dumps(incident, indent=2)])

    labels = Labels(scenario_id=sc.scenario_id, fault=sc.fault, classification=spec["classification"],
                    outcome=spec["outcome"], leading_categories=spec["leading"],
                    forbidden_categories=spec["forbidden"], required_missing=spec.get("required_missing", []),
                    key_lines=key_lines, total_lines=total, components=spec.get("components", []))
    _write(out / "labels" / f"{sc.scenario_id}.json", [labels.model_dump_json(indent=2)])
    return labels


def _write(path: Path, lines: list[str]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
